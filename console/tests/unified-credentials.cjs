const { chromium } = require(process.env.PRISM_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const base = process.env.PRISM_TEST_BASE_URL;
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));

(async () => {
  assert(base && new URL(base).hostname === '127.0.0.1', 'isolated test server required');
  const browser = await chromium.launch({ channel: process.env.PRISM_BROWSER_CHANNEL || 'msedge', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const login = await context.request.post(base + '/api/auth/login', { data: { username: 'qa-admin', password: process.env.PRISM_TEST_PASSWORD } });
    const auth = await login.json();
    assert.equal(auth.code, 0, 'real console authentication');
    await context.addInitScript(token => localStorage.setItem('prism_token', token), auth.data.token);
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', err => errors.push(err.message));
    await page.goto(base + '/#/unified-gateway');
    await page.getByRole('tab', { name: '网关管理' }).click();
    await page.getByRole('button', { name: '新建网关', exact: true }).click();
    let dialog = page.getByRole('dialog');
    await dialog.getByLabel('渠道名称', { exact: true }).fill('Credential QA');
    await dialog.getByLabel('渠道标识', { exact: true }).fill('credential-qa');
    await dialog.getByRole('button', { name: '创建渠道', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('row').filter({ hasText: 'Credential QA' }).click();
    await page.getByRole('button', { name: '新建 Key 分组', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Key 池名称', { exact: true }).fill('Pool QA');
    await dialog.getByLabel('Key 池标识', { exact: true }).fill('pool-qa');
    await dialog.getByRole('button', { name: '创建 Key 池', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '添加 API Key', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Key 名称', { exact: true }).fill('key-qa');
    await dialog.getByLabel('密钥', { exact: true }).fill('isolated-browser-secret');
    await dialog.getByLabel('权重', { exact: true }).fill('7');
    await dialog.getByRole('checkbox', { name: '任务并发不限' }).uncheck();
    await dialog.getByRole('spinbutton', { name: '任务并发', exact: true }).fill('3');
    await dialog.getByRole('button', { name: '保存', exact: true }).dblclick();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByText('key-qa', { exact: true }).waitFor();
    const headers = { Authorization: `Bearer ${auth.data.token}` };
    const list = async () => (await (await context.request.get(base + '/api/admin/unified-gateway/credentials', { headers })).json()).data;
    let data = await list();
    assert.equal(data.total, 1, 'double click creates one credential');
    assert.equal(data.items[0].weight, 7);
    assert.equal(data.items[0].task_limit, 3);
    assert.deepEqual(data.items[0].purposes, ['execution']);
    assert(!JSON.stringify(data).includes('isolated-browser-secret'), 'metadata API does not expose secrets');
    const item = data.items[0];
    const denied = await context.request.get(base + '/api/admin/unified-gateway/credentials');
    assert.equal(denied.status(), 401, 'unauthenticated metadata access denied');
    await page.getByRole('button', { name: '编辑凭据', exact: true }).click();
    dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel('密钥', { exact: true }).count(), 0, 'editing never loads a secret');
    await dialog.getByLabel('权重', { exact: true }).fill('9');
    const competing = await context.request.put(`${base}/api/admin/unified-gateway/credentials/${item.id}`, { headers, data: { weight: 8, request_limit: null, task_limit: 3, expected_version: item.config_version } });
    assert.equal(competing.status(), 200);
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await dialog.getByText(/配置状态已变化/).waitFor();
    await dialog.getByRole('button', { name: '取消', exact: true }).click();
    await page.getByRole('button', { name: '刷新', exact: true }).click();
    await page.getByText('key-qa', { exact: true }).waitFor();
    await page.getByRole('button', { name: '编辑凭据', exact: true }).click();
    dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel('权重', { exact: true }).inputValue(), '8');
    await dialog.getByLabel('权重', { exact: true }).fill('9');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal((await list()).items[0].weight, 9);
    await page.getByRole('button', { name: '新建凭据', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('凭据标识', { exact: true }).fill('duplicate-qa');
    await dialog.getByLabel('密钥', { exact: true }).fill('isolated-browser-secret');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await dialog.getByText('密钥已存在于该渠道', { exact: true }).waitFor();
    await dialog.getByRole('button', { name: '取消', exact: true }).click();
    assert.equal((await list()).total, 1);
    await delay(400);
    await page.screenshot({ path: path.resolve('../.temp/qa_credentials_real_desktop_20260905.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await delay(400);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile page has no horizontal overflow');
    await page.screenshot({ path: path.resolve('../.temp/qa_credentials_real_mobile_20260905.png'), fullPage: true });
    await page.getByRole('button', { name: '新建凭据', exact: true }).click();
    await delay(400);
    await page.screenshot({ path: path.resolve('../.temp/qa_credentials_real_dialog_20260905.png'), fullPage: true });
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: '停止分配凭据', exact: true }).click();
    await page.getByRole('button', { name: '确认', exact: true }).click();
    await page.getByRole('button', { name: '停用凭据', exact: true }).waitFor();
    await page.getByRole('alertdialog').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '停用凭据', exact: true }).click();
    await page.getByRole('button', { name: '确认', exact: true }).click();
    await page.getByRole('alertdialog').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '停用凭据', exact: true }).waitFor({ state: 'hidden' });
    assert.equal((await list()).items[0].status, 'disabled');
    await page.reload();
    await page.getByRole('tab', { name: '凭据', exact: true }).click();
    await page.getByText('key-qa', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: '编辑凭据', exact: true }).isDisabled(), true);
    await context.route('**/api/admin/unified-gateway/overview', async route => {
      const response = await route.fetch();
      const body = await response.json();
      delete body.data.management_revision;
      await route.fulfill({ response, json: body });
    });
    await page.getByRole('button', { name: '刷新', exact: true }).click();
    await page.getByRole('tab', { name: '网关管理' }).click();
    await page.getByText('Credential QA', { exact: true }).waitFor();
    assert(await page.getByRole('button', { name: '新建网关', exact: true }).isDisabled(), 'old backends remain read-only');
    await require('./unified-request-logs.cjs')(context, page, base);
    assert.deepEqual(errors, []);
    console.log('PASS real authentication, MySQL CRUD, encryption metadata, duplicate protection, version conflicts, status lifecycle, desktop/mobile and reload persistence');
  } finally { await browser.close(); }
})().catch(err => { console.error(err); process.exitCode = 1; });
